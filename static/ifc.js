// Builds an IFC4 (ISO 10303-21) model from floor plan detections.
//
// Plan axes map to IFC as x -> +X and image-down -> -Y, with Z up, so the model
// reads the same way as the image when seen from above.

import { footprint, verticalExtent } from './layout.js';

// Overlap below this (meters) is treated as boxes merely touching.
const TOUCH_M = 0.01;
// An opening is hosted by a wall (and cuts it) only if it overlaps this much along the wall;
// less than that means the wall just ends next to the opening.
const HOST_MIN_OVERLAP_M = 0.1;
// An opening with no overlapping wall still borrows the orientation of a wall this close.
const NEAR_WALL_M = 0.15;
// Openings without any nearby wall get at most this thickness.
const MAX_FREE_THICKNESS_M = 0.25;
// Voids are made slightly thicker than their wall so the cut is clean.
const VOID_EXTRA_M = 0.02;

const STYLES = {
  wall: { rgb: [0.486, 0.522, 0.580], transparency: 0 },
  door: { rgb: [0.851, 0.467, 0.024], transparency: 0.2 },
  window: { rgb: [0.008, 0.518, 0.780], transparency: 0.55 },
};

/**
 * @param {object} input
 * @param {string} input.name          project name, usually the image file name
 * @param {Array}  input.detections    [{cls, score, x1, y1, x2, y2}] in pixels
 * @param {object} input.plan          {width, height, metersPerPx}
 * @param {number} input.wallHeight    meters
 * @param {Date}   [input.timestamp]
 * @returns {string} IFC4 STEP file contents
 */
export function buildIfc({ name, detections, plan, wallHeight, timestamp = new Date() }) {
  const w = new StepWriter();
  const walls = detections.filter((d) => d.cls === 'wall').map((d) => wallBox(d, plan, wallHeight));
  const openings = detections.filter((d) => d.cls === 'door' || d.cls === 'window')
    .map((d) => openingBox(d, plan, wallHeight, walls));

  // ------------------------------------------------------------ project setup
  const origin = w.add('IFCCARTESIANPOINT', list([real(0), real(0), real(0)]));
  const zAxis = w.add('IFCDIRECTION', list([real(0), real(0), real(1)]));
  const xAxis = w.add('IFCDIRECTION', list([real(1), real(0), real(0)]));
  const yAxis = w.add('IFCDIRECTION', list([real(0), real(1), real(0)]));
  const worldAxes = w.add('IFCAXIS2PLACEMENT3D', origin, zAxis, xAxis);
  const upDirection = zAxis;

  const context = w.add('IFCGEOMETRICREPRESENTATIONCONTEXT', $, str('Model'), 3, real(1e-5), worldAxes, $);
  const bodyContext = w.add('IFCGEOMETRICREPRESENTATIONSUBCONTEXT',
    str('Body'), str('Model'), '*', '*', '*', '*', context, $, '.MODEL_VIEW.', $);
  const axisContext = w.add('IFCGEOMETRICREPRESENTATIONSUBCONTEXT',
    str('Axis'), str('Model'), '*', '*', '*', '*', context, $, '.GRAPH_VIEW.', $);

  const units = w.add('IFCUNITASSIGNMENT', list([
    w.add('IFCSIUNIT', '*', '.LENGTHUNIT.', $, '.METRE.'),
    w.add('IFCSIUNIT', '*', '.AREAUNIT.', $, '.SQUARE_METRE.'),
    w.add('IFCSIUNIT', '*', '.VOLUMEUNIT.', $, '.CUBIC_METRE.'),
    w.add('IFCSIUNIT', '*', '.PLANEANGLEUNIT.', $, '.RADIAN.'),
  ]));

  const project = w.add('IFCPROJECT', guid(), $, str(name), str('Generated by FloorPlanTo3D from Mask R-CNN detections'),
    $, $, $, list([context]), units);

  const placementAt = (relTo, x, y, z, alongY = false) => w.add('IFCLOCALPLACEMENT', relTo,
    w.add('IFCAXIS2PLACEMENT3D', w.add('IFCCARTESIANPOINT', list([real(x), real(y), real(z)])), upDirection,
      alongY ? yAxis : xAxis));

  const sitePlacement = placementAt($, 0, 0, 0);
  const site = w.add('IFCSITE', guid(), $, str('Site'), $, $, sitePlacement, $, $, '.ELEMENT.', $, $, $, $, $);
  const buildingPlacement = placementAt(sitePlacement, 0, 0, 0);
  const building = w.add('IFCBUILDING', guid(), $, str('Building'), $, $, buildingPlacement, $, $, '.ELEMENT.', $, $, $);
  const storeyPlacement = placementAt(buildingPlacement, 0, 0, 0);
  const storey = w.add('IFCBUILDINGSTOREY', guid(), $, str('Ground Floor'), $, $, storeyPlacement, $, $, '.ELEMENT.', real(0));

  w.add('IFCRELAGGREGATES', guid(), $, $, $, project, list([site]));
  w.add('IFCRELAGGREGATES', guid(), $, $, $, site, list([building]));
  w.add('IFCRELAGGREGATES', guid(), $, $, $, building, list([storey]));

  // ------------------------------------------------------------ shared styling
  const surfaceStyles = {};
  const materials = {};
  for (const [cls, style] of Object.entries(STYLES)) {
    const colour = w.add('IFCCOLOURRGB', $, ...style.rgb.map(real));
    const rendering = w.add('IFCSURFACESTYLERENDERING', colour, real(style.transparency), $, $, $, $, $, $, '.NOTDEFINED.');
    surfaceStyles[cls] = w.add('IFCSURFACESTYLE', str(cls), '.BOTH.', list([rendering]));
    materials[cls] = w.add('IFCMATERIAL', str(capitalize(cls)), $, str(capitalize(cls)));
  }

  // Box solid of the given size, extruded up from local z = 0.
  const bodyShape = (cls, length, thickness, height) => {
    const profile = w.add('IFCRECTANGLEPROFILEDEF', '.AREA.', $,
      w.add('IFCAXIS2PLACEMENT2D', w.add('IFCCARTESIANPOINT', list([real(0), real(0)])), $),
      real(length), real(thickness));
    const solid = w.add('IFCEXTRUDEDAREASOLID', profile,
      w.add('IFCAXIS2PLACEMENT3D', origin, $, $), upDirection, real(height));
    if (cls) w.add('IFCSTYLEDITEM', solid, list([surfaceStyles[cls]]), $);
    return w.add('IFCSHAPEREPRESENTATION', bodyContext, str('Body'), str('SweptSolid'), list([solid]));
  };

  const contained = [];
  const byClass = { wall: [], door: [], window: [] };
  const addDetectionPset = (element, d) => {
    const props = [
      w.add('IFCPROPERTYSINGLEVALUE', str('Confidence'), $, typed('IFCNORMALISEDRATIOMEASURE', real(d.score)), $),
      w.add('IFCPROPERTYSINGLEVALUE', str('BoundingBoxPx'), $,
        typed('IFCLABEL', str(`${d.x1},${d.y1},${d.x2},${d.y2}`)), $),
    ];
    const pset = w.add('IFCPROPERTYSET', guid(), $, str('FloorPlanTo3D_Detection'), $, list(props));
    w.add('IFCRELDEFINESBYPROPERTIES', guid(), $, $, $, list([element]), pset);
  };

  // ------------------------------------------------------------ walls
  walls.forEach((box, i) => {
    const placement = placementAt(storeyPlacement, box.cx, box.cy, box.bottom, box.alongY);
    const axis = w.add('IFCSHAPEREPRESENTATION', axisContext, str('Axis'), str('Curve2D'), list([
      w.add('IFCPOLYLINE', list([
        w.add('IFCCARTESIANPOINT', list([real(-box.length / 2), real(0)])),
        w.add('IFCCARTESIANPOINT', list([real(box.length / 2), real(0)])),
      ])),
    ]));
    const shape = w.add('IFCPRODUCTDEFINITIONSHAPE', $, $,
      list([axis, bodyShape('wall', box.length, box.thickness, box.top - box.bottom)]));
    box.placement = placement;
    box.entity = w.add('IFCWALL', guid(), $, str(`Wall ${i + 1}`), $, $, placement, shape, $, '.STANDARD.');
    addDetectionPset(box.entity, box.d);
    contained.push(box.entity);
    byClass.wall.push(box.entity);
  });

  // ------------------------------------------------------------ doors and windows
  const counters = { door: 0, window: 0 };
  for (const box of openings) {
    const cls = box.d.cls;
    const height = box.top - box.bottom;
    const placement = placementAt(storeyPlacement, box.cx, box.cy, box.bottom, box.alongY);
    const shape = w.add('IFCPRODUCTDEFINITIONSHAPE', $, $, list([bodyShape(cls, box.length, box.thickness, height)]));
    const label = str(`${capitalize(cls)} ${++counters[cls]}`);
    const element = cls === 'door'
      ? w.add('IFCDOOR', guid(), $, label, $, $, placement, shape, $, real(height), real(box.length), '.DOOR.', '.NOTDEFINED.', $)
      : w.add('IFCWINDOW', guid(), $, label, $, $, placement, shape, $, real(height), real(box.length), '.WINDOW.', '.NOTDEFINED.', $);
    addDetectionPset(element, box.d);
    contained.push(element);
    byClass[cls].push(element);

    // Cut every wall this opening sits in; the one it overlaps most is also filled by it.
    box.hosts.forEach((wall, hostIndex) => {
      // Offset of the opening within the wall's local axes (x along the wall, y across it).
      const dx = box.cx - wall.cx;
      const dy = box.cy - wall.cy;
      const localX = wall.alongY ? dy : dx;
      const localY = wall.alongY ? -dx : dy;
      // Doors start at the floor, so let their void start just below it.
      const voidBottom = box.bottom === 0 ? -VOID_EXTRA_M : box.bottom;
      const voidPlacement = w.add('IFCLOCALPLACEMENT', wall.placement,
        w.add('IFCAXIS2PLACEMENT3D',
          w.add('IFCCARTESIANPOINT', list([real(localX), real(localY), real(voidBottom - wall.bottom)])), $, $));
      const voidShape = w.add('IFCPRODUCTDEFINITIONSHAPE', $, $,
        list([bodyShape(null, box.length, wall.thickness + VOID_EXTRA_M, box.top - voidBottom)]));
      const opening = w.add('IFCOPENINGELEMENT', guid(), $, str(`Opening for ${capitalize(cls)} ${counters[cls]}`), $, $,
        voidPlacement, voidShape, $, '.OPENING.');
      w.add('IFCRELVOIDSELEMENT', guid(), $, $, $, wall.entity, opening);
      if (hostIndex === 0) w.add('IFCRELFILLSELEMENT', guid(), $, $, $, opening, element);
    });
  }

  if (contained.length) {
    w.add('IFCRELCONTAINEDINSPATIALSTRUCTURE', guid(), $, $, $, list(contained), storey);
  }
  for (const [cls, elements] of Object.entries(byClass)) {
    if (elements.length) w.add('IFCRELASSOCIATESMATERIAL', guid(), $, $, $, list(elements), materials[cls]);
  }

  return w.toString(name, timestamp);
}

// ---------------------------------------------------------------- geometry

function wallBox(d, plan, wallHeight) {
  const f = footprint(d, plan);
  const { bottom, top } = verticalExtent('wall', wallHeight);
  const alongY = f.sy > f.sx;
  const box = {
    d,
    cx: f.cx,
    cy: -f.cy,
    alongY,
    length: alongY ? f.sy : f.sx,
    thickness: alongY ? f.sx : f.sy,
    bottom,
    top,
  };
  return withBounds(box);
}

// Fits a door or window into the wall it belongs to: it takes the wall's direction,
// thickness and centerline, and keeps its own extent along the wall.
function openingBox(d, plan, wallHeight, walls) {
  const f = footprint(d, plan);
  const { bottom, top } = verticalExtent(d.cls, wallHeight);
  const raw = withBounds({ cx: f.cx, cy: -f.cy, alongY: f.sy > f.sx, length: Math.max(f.sx, f.sy), thickness: Math.min(f.sx, f.sy) });

  const overlapping = walls
    .map((wall) => ({ wall, ...overlap(raw, wall) }))
    .filter((o) => o.x > TOUCH_M && o.y > TOUCH_M)
    .sort((a, b) => b.x * b.y - a.x * a.y);

  let reference = overlapping[0]?.wall;
  if (!reference) {
    reference = walls
      .map((wall) => ({ wall, gap: gap(raw, wall) }))
      .filter((o) => o.gap <= NEAR_WALL_M)
      .sort((a, b) => a.gap - b.gap)[0]?.wall;
  }

  const box = { d, bottom, top, hosts: [] };
  if (reference) {
    box.alongY = reference.alongY;
    box.thickness = reference.thickness;
    if (box.alongY) {
      box.cx = reference.cx;
      box.cy = raw.cy;
      box.length = raw.maxY - raw.minY;
    } else {
      box.cx = raw.cx;
      box.cy = reference.cy;
      box.length = raw.maxX - raw.minX;
    }
    // Only walls running the same way are cut; a crossing wall at a corner is left whole.
    box.hosts = overlapping
      .filter((o) => o.wall.alongY === box.alongY && (box.alongY ? o.y : o.x) >= HOST_MIN_OVERLAP_M)
      .map((o) => o.wall);
  } else {
    Object.assign(box, raw, { thickness: Math.min(raw.thickness, MAX_FREE_THICKNESS_M) });
  }
  return box;
}

function withBounds(box) {
  const halfX = (box.alongY ? box.thickness : box.length) / 2;
  const halfY = (box.alongY ? box.length : box.thickness) / 2;
  return Object.assign(box, {
    minX: box.cx - halfX, maxX: box.cx + halfX, minY: box.cy - halfY, maxY: box.cy + halfY,
  });
}

function overlap(a, b) {
  return {
    x: Math.min(a.maxX, b.maxX) - Math.max(a.minX, b.minX),
    y: Math.min(a.maxY, b.maxY) - Math.max(a.minY, b.minY),
  };
}

function gap(a, b) {
  const o = overlap(a, b);
  return Math.hypot(Math.max(0, -o.x), Math.max(0, -o.y));
}

// ---------------------------------------------------------------- STEP encoding

const $ = '$';

class StepWriter {
  constructor() {
    this.lines = [];
  }

  add(type, ...args) {
    const id = `#${this.lines.length + 1}`;
    this.lines.push(`${id}=${type}(${args.join(',')});`);
    return id;
  }

  toString(name, timestamp) {
    const time = timestamp.toISOString().replace(/\.\d+Z$/, '');
    return [
      'ISO-10303-21;',
      'HEADER;',
      "FILE_DESCRIPTION(('ViewDefinition [DesignTransferView]'),'2;1');",
      `FILE_NAME(${str(fileName(name))},${str(time)},(''),(''),'FloorPlanTo3D','FloorPlanTo3D viewer','');`,
      "FILE_SCHEMA(('IFC4'));",
      'ENDSEC;',
      'DATA;',
      ...this.lines,
      'ENDSEC;',
      'END-ISO-10303-21;',
      '',
    ].join('\n');
  }
}

function list(items) {
  return `(${items.join(',')})`;
}

function typed(type, value) {
  return `${type}(${value})`;
}

// STEP reals always carry a decimal point and never use exponent notation here.
function real(n) {
  if (!Number.isFinite(n)) throw new Error(`Cannot write ${n} to IFC`);
  if (Math.abs(n) < 1e-9) return '0.';
  const text = Math.abs(n) < 1e-3 ? n.toExponential(6).replace(/e/, 'E') : n.toFixed(6).replace(/0+$/, '');
  return text.includes('.') ? text : `${text}.`;
}

// STEP strings escape quotes and backslashes, and encode non-ASCII as \X2\ UTF-16 hex.
function str(value) {
  let out = '';
  for (const ch of String(value)) {
    const code = ch.codePointAt(0);
    if (ch === "'") out += "''";
    else if (ch === '\\') out += '\\\\';
    else if (code >= 0x20 && code <= 0x7e) out += ch;
    else {
      // Astral characters become a surrogate pair of UTF-16 code units.
      const units = Array.from({ length: ch.length }, (_, i) => ch.charCodeAt(i));
      out += `\\X2\\${units.map((u) => u.toString(16).toUpperCase().padStart(4, '0')).join('')}\\X0\\`;
    }
  }
  return `'${out}'`;
}

const GUID_CHARS = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_$';

// 22-character IFC GlobalId from 128 random bits. getRandomValues also works on
// plain http origins, unlike randomUUID.
function guid() {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // RFC 4122 version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  let n = bytes.reduce((acc, b) => (acc << 8n) | BigInt(b), 0n);
  const chars = new Array(22);
  for (let i = 21; i >= 0; i--) {
    chars[i] = GUID_CHARS[Number(n & 63n)];
    n >>= 6n;
  }
  return str(chars.join(''));
}

function fileName(name) {
  return `${name.replace(/\.[^.]+$/, '')}.ifc`;
}

function capitalize(s) {
  return s[0].toUpperCase() + s.slice(1);
}
